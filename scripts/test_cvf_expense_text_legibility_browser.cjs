// One read-only measurement pass: geometry and colors in the page, assertions in Node.
const probe = (page) => page.evaluate(() => {
  const q = (s) => document.querySelector(s), all = (s) => [...document.querySelectorAll(s)], cs = (e) => getComputedStyle(e);
  const num = (v) => parseFloat(v) || 0, nums = (c) => c.match(/[\d.]+/g).map(Number);
  const box = (el) => { const r = el.getBoundingClientRect(); return { l: r.left, r: r.right, t: r.top, b: r.bottom, w: r.width, h: r.height }; };
  const inner = (el) => { const r = box(el), s = cs(el); return { l: r.l + num(s.borderLeftWidth) + num(s.paddingLeft), r: r.r - num(s.borderRightWidth) - num(s.paddingRight), t: r.t + num(s.borderTopWidth) + num(s.paddingTop), b: r.b - num(s.borderBottomWidth) - num(s.paddingBottom) }; };
  const lines = (el) => {
    const out = [], walker = document.createTreeWalker(el, NodeFilter.SHOW_TEXT);
    for (let n = walker.nextNode(); n; n = walker.nextNode()) { const rg = document.createRange(); rg.selectNodeContents(n); for (const x of rg.getClientRects()) out.push({ l: x.left, r: x.right, t: x.top, b: x.bottom }); }
    return out;
  };
  const effectiveBg = (el) => {
    const layers = [];
    for (let e = el; e; e = e.parentElement) {
      const c = nums(cs(e).backgroundColor), a = c.length > 3 ? c[3] : 1;
      if (a > 0) layers.push({ rgb: c.slice(0, 3), a });
      if (a === 1) break;
    }
    let base = layers.length && layers[layers.length - 1].a === 1 ? layers.pop().rgb : [255, 255, 255];
    while (layers.length) { const { rgb, a } = layers.pop(); base = base.map((v, i) => rgb[i] * a + v * (1 - a)); }
    return base;
  };
  const role = (name, el) => ({ role: name, text: el.textContent.trim().slice(0, 20), css: cs(el).color, fg: nums(cs(el).color).slice(0, 3), bg: effectiveBg(el) });
  const input = q('input[type=month]'), note = q('p[role=note]'), table = q('#root table'), section = q('#root section');
  const title = q('#root h2'), label = q('#root label'), status = q('#root [role=status]');
  return {
    ids: all('[data-expense-id]').map((el) => el.dataset.expenseId), tables: all('#root table').length, status: status ? status.textContent : null,
    body: document.body.innerText, hscroll: document.documentElement.scrollWidth - window.innerWidth, sectionOverflow: section.scrollWidth - section.clientWidth,
    content: inner(section), input: box(input), note: box(note), noteLines: lines(note), table: table ? box(table) : null,
    pageBg: nums(cs(document.body).backgroundColor).slice(0, 3), surface: effectiveBg(title),
    cells: all('#root th, #root td').map((c) => ({ tag: c.tagName, text: c.textContent, box: box(c), inner: inner(c), lines: lines(c) })),
    roles: [...all('#root th').map((e) => role('HEADER_TEXT_CONTRAST', e)), ...all('#root tbody td').map((e) => role('ROW_TEXT_CONTRAST', e)),
      role('TITLE_TEXT_CONTRAST', title), role('LABEL_TEXT_CONTRAST', label), role('NOTICE_TEXT_CONTRAST', note),
      ...(status ? [role('EMPTY_MESSAGE_CONTRAST', status)] : []), role('MONTH_TEXT_CONTRAST', input)],
    semantics: { labelText: label.textContent, labelControlIsInput: label.control === input, inputType: input.type, boxSizing: cs(input).boxSizing,
      sectionLabelledBy: section.getAttribute('aria-labelledby') === title.id, tableLabelledBy: table ? table.getAttribute('aria-labelledby') === title.id : null,
      scopes: all('#root th').map((th) => th.getAttribute('scope')) },
  };
});

const within = (r, bounds, label) => check(r.l >= bounds.l - TOL && r.r <= bounds.r + TOL && r.t >= bounds.t - TOL && r.b <= bounds.b + TOL,
  label + ' outside bounds: x ' + r.l.toFixed(1) + '-' + r.r.toFixed(1) + ' vs ' + bounds.l.toFixed(1) + '-' + bounds.r.toFixed(1));
// The 44px target plus containment of real rectangles in the section content box and cell inner boxes.
function layout(s, label) {
  check(s.input.h >= 44 && s.input.w >= 44 && s.semantics.boxSizing === 'border-box', 'touch target<44: ' + label + ' input ' + s.input.w + 'x' + s.input.h);
  if (s.table) {
    within(s.table, s.content, label + ' table rectangle');
    for (const c of s.cells) {
      within(c.box, s.content, label + ' cell "' + c.text.slice(0, 10) + '" rectangle');
      for (const r of c.lines) within(r, c.inner, label + ' text line of "' + c.text.slice(0, 10) + '"');
    }
    for (const amount of s.cells.filter((c) => c.tag === 'TD' && /^\d+$/.test(c.text))) {
      check(new Set(amount.lines.map((r) => Math.round(r.t))).size === 1, label + ' amount ' + amount.text + ' on a single line');
    }
  }
  within(s.note, s.content, label + ' notice rectangle');
  for (const r of s.noteLines) within(r, s.note, label + ' notice text line');
  within(s.input, s.content, label + ' input rectangle');
  check(s.hscroll <= 0 && s.sectionOverflow <= TOL, label + ' no document or section horizontal overflow');
}
// Exact text oracle, native month input with linked label, table association and scope=col.
function literal(s, ids, label) {
  const rows = ROWS.filter((r) => ids.includes(r.id)).map((r) => [r.date, r.label, String(r.amount)]), m = s.semantics;
  same(s.cells.filter((c) => c.tag === 'TH').map((c) => c.text), s.table ? HEADERS : [], label + ' header text');
  same(s.cells.filter((c) => c.tag === 'TD').map((c) => c.text), rows.flat(), label + ' cell text equality');
  same([m.labelText, m.labelControlIsInput, m.inputType, m.sectionLabelledBy], [LABEL_TEXT, true, 'month', true], label + ' native month input and linked label');
  if (s.table) same([m.tableLabelledBy, m.scopes], [true, ['col', 'col', 'col']], label + ' table association and scope=col');
}
// Every text role: unrounded contrast >= 4.5 first (header first), then the exact semantic role token and background.
function textContrast(s, profile, name, label) {
  lastRoles = s.roles.map((r) => ({ role: r.role, text: r.text, fg: r.css, ratio: round4(ratio(r.fg, r.bg)) }));
  for (const r of s.roles) {
    const value = ratio(r.fg, r.bg);
    check(value >= MIN_TEXT, `${r.role} ratio ${value} < ${MIN_TEXT} (${label} "${r.text}" ${r.css} on rgb(${r.bg.map(Math.round).join(', ')}))`);
  }
  for (const r of s.roles) {
    const [fgToken, bgToken] = ROLE_TOKENS[r.role], bg = 'rgb(' + r.bg.map(Math.round).join(', ') + ')';
    same([r.css, bg], [rgbCss(hexRgb(profile.theme[fgToken])), rgbCss(hexRgb(profile.theme[bgToken]))], `${label} ${r.role} expected ${fgToken} on ${bgToken}`);
    roleLog.push({ profile: name, state: label, role: r.role, text: r.text, color: r.css, background: bg, ratio: round4(ratio(r.fg, r.bg)), fgToken, bgToken });
  }
}
// Keyboard Tab from a blurred page: the input is focused with a computed 2px accent outline contrasting >= 3 with its surroundings.
async function focusCheck(page, profile, name, label) {
  await page.evaluate(() => { if (document.activeElement) document.activeElement.blur(); });
  await page.keyboard.press('Tab');
  const f = await page.evaluate(() => {
    const el = document.activeElement, cs = getComputedStyle(el);
    return { tag: el.tagName, type: el.type, visible: el.matches(':focus-visible'), style: cs.outlineStyle, width: cs.outlineWidth, color: cs.outlineColor, offset: cs.outlineOffset };
  });
  const s = await probe(page), accent = hexRgb(profile.accent);
  check(f.tag === 'INPUT' && f.type === 'month' && f.visible, label + ' Tab focuses the visible month input');
  same([f.style, f.width, f.offset, f.color], ['solid', '2px', '2px', rgbCss(accent)], label + ' focus outline is 2px accent');
  check(ratio(accent, s.surface) >= MIN_FOCUS && ratio(accent, s.pageBg) >= MIN_FOCUS, `${label} focus indicator contrast vs surface and page >= ${MIN_FOCUS}`);
  focusLog.push({ profile: name, state: label, outline: `${f.width} ${f.style} ${f.color}`, vsSurface: round4(ratio(accent, s.surface)), vsPage: round4(ratio(accent, s.pageBg)) });
}
// Initial -> March -> April (empty) -> clear with text, focus and layout checks in every state. quick = March only.
async function flow(page, name, profile, quick) {
  const month = page.getByLabel(LABEL_TEXT);
  await page.waitForSelector('#root table tbody tr', { timeout: TIMEOUT });
  let s = await probe(page);
  if (!quick) {
    same(s.ids, CLEAR_IDS, name + ' initial view shows four valid rows in source order');
    check(!s.body.includes(INVALID_TEXT) && !s.body.includes('05/03/2026') && s.body.includes(NOTICE), name + ' invalid row absent and notice present');
    await focusCheck(page, profile, name, name + ' initial');
  }
  await month.fill('2026-03');
  s = await probe(page);
  same(s.ids, MARCH_IDS, name + ' March shows the two March rows');
  layout(s, name + ' March'); literal(s, MARCH_IDS, name + ' March');
  layoutPassedFirst = true;
  textContrast(s, profile, name, name + ' March');
  if (quick) return;
  const file = path.join(OUT, 'march-' + name + '.png');
  await page.screenshot({ path: file, fullPage: true });
  const png = fs.readFileSync(file);
  check(png.length <= MAX_PNG, name + ' screenshot within 3 MiB');
  shots.push({ profile: name, path: posix(path.relative(ROOT, file)), bytes: png.length, sha256: sha256(png) });
  await month.fill('2026-04');
  s = await probe(page);
  same([s.ids, s.tables, s.status], [[], 0, EMPTY_TEXT], name + ' April shows the exact empty message and no table');
  layout(s, name + ' April'); literal(s, [], name + ' April'); textContrast(s, profile, name, name + ' April');
  await focusCheck(page, profile, name, name + ' April');
  await month.fill('');
  s = await probe(page);
  same(s.ids, CLEAR_IDS, name + ' clearing restores four valid rows');
  layout(s, name + ' clear'); literal(s, CLEAR_IDS, name + ' clear'); textContrast(s, profile, name, name + ' clear');
}

async function runCase(label, name, pageFile, quick) {
  const profile = PROFILES[name], t0 = Date.now(), before = assertions, net = { external: [], errors: [] };
  let status = 'PASS', failureKind = null, error = null, ctx = null;
  try {
    ctx = await browser.newContext({ viewport: { width: profile.width, height: profile.height }, deviceScaleFactor: 1 });
    const page = await ctx.newPage();
    page.setDefaultTimeout(TIMEOUT);
    await ctx.route('**/*', (route) => (route.request().url().startsWith('file:') ? route.continue() : route.abort()));
    page.on('request', (req) => { if (!req.url().startsWith('file:')) net.external.push(req.url()); });
    page.on('pageerror', (e) => net.errors.push('pageerror: ' + e.message));
    page.on('console', (m) => { if (m.type() === 'error') net.errors.push('console: ' + m.text()); });
    await page.goto(pathToFileURL(pageFile).href);
    await flow(page, name, profile, quick);
  } catch (e) {
    status = 'FAIL'; failureKind = e.name === 'AssertionError' ? 'ASSERTION' : 'HARNESS_OR_RUNTIME'; error = String(e.message || e).slice(0, 400);
  } finally { if (ctx) await ctx.close(); }
  if (net.external.length) { status = 'FAIL'; failureKind = failureKind || 'EXTERNAL_REQUEST'; }
  if (net.errors.length) { status = 'FAIL'; failureKind = failureKind || 'PAGE_ERROR'; error = error || net.errors.join(' | ').slice(0, 400); }
  const record = { label, profile: name, status, failureKind, assertions: assertions - before, ms: Date.now() - t0, error, externalRequests: net.external.length, pageErrors: net.errors.length };
  results.push(record);
  console.log(`${status} ${label} ${name}${error ? ' :: ' + error : ''}`);
  return record;
}
// Source-pin sentinel: this same script runs on an ignored copy with one changed byte and must refuse before any write.
function runSentinel() {
  const hashAll = () => Object.fromEntries(fs.readdirSync(OUT, { recursive: true }).map((rel) => path.join(OUT, rel))
    .filter((file) => !file.startsWith(SENTINEL_DIR) && fs.statSync(file).isFile()).map((file) => [posix(path.relative(OUT, file)), sha256(fs.readFileSync(file))]));
  fs.mkdirSync(SENTINEL_DIR, { recursive: true });
  const copy = path.join(SENTINEL_DIR, 'ExpenseList.sentinel.tsx');
  fs.writeFileSync(copy, fs.readFileSync(DEFAULT_SOURCE, 'utf8') + '\n// sentinel byte drift\n', 'utf8');
  const before = hashAll(), child = childProcess.spawnSync(process.execPath, [__filename, '--source', copy], { encoding: 'utf8' }), after = hashAll();
  return { copySha256: sha256(fs.readFileSync(copy)), exit: child.status, stderr: child.stderr.trim().slice(0, 200), stdoutBytes: child.stdout.length,
    refused: child.status === 3 && /SOURCE_PIN_DRIFT/.test(child.stderr) && child.stdout === '',
    noWrites: JSON.stringify(before) === JSON.stringify(after), artifactsBefore: Object.keys(before).length, artifactsAfter: Object.keys(after).length };
}
